    (select count(*) from public.site_content
      where key in ('looks.title','looks.subtitle','order.confirm.text',
                    'checkout.hint.phone','checkout.hint.address','checkout.consent.text',
                    'checkout.promo.placeholder','checkout.promo.apply',
