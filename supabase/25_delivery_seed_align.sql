-- ----------------------------------------------------------------------------
-- 0. Префлайт: убеждаемся, что мы в проекте черновика Sisku, а не в учебном
--    (правило 6 supabase/README.md).
-- ----------------------------------------------------------------------------
do $$
begin
    if to_regclass('public.delivery_methods') is null
       or to_regclass('public.site_content') is null then
        raise exception 'Sisku draft: не найдены таблицы черновика (delivery_methods / site_content). Проверьте переключатель проектов Supabase слева вверху: нужен проект sisku-draft, а не учебный.';
    end if;
end $$;

-- ----------------------------------------------------------------------------
-- 1. Способ доставки: Boxberry → Почта России (guard по старому коду)
-- ----------------------------------------------------------------------------
update public.delivery_methods
   set code = 'pochtaruss',
       name = 'Почта России, 3–8 дней'
 where code = 'boxberry';

-- ----------------------------------------------------------------------------
-- 2. Тексты site_content: «Boxberry» → «Почта России» (guard по старому
--    значению; только ключи посевов 04/20, где название встречается)
-- ----------------------------------------------------------------------------
update public.site_content
   set value      = replace(value, 'Boxberry', 'Почта России'),
       updated_at = now()
 where key in ('order.delivery.text', 'adv.3.text', 'checkout.hint.address')
   and value like '%Boxberry%';

-- ----------------------------------------------------------------------------
-- 3. Самопроверка
-- ----------------------------------------------------------------------------
select
    (select count(*) from public.delivery_methods
      where code = 'boxberry')                            as boxberry_left,     -- ждём 0
    (select count(*) from public.delivery_methods
      where code = 'pochtaruss')                          as pochtaruss_rows,   -- ждём 1
    (select name from public.delivery_methods
      where code = 'pochtaruss')                          as pochtaruss_name,   -- ждём «Почта России, 3–8 дней»
    (select count(*) from public.site_content
      where value like '%Boxberry%')                      as texts_with_boxberry, -- ждём 0
    (select value from public.site_content
      where key = 'order.delivery.text')                 as delivery_text;     -- на новой базе — «…СДЭК и Почта России по России…»; на живой — текст владельца (не изменён)
