--  Посевы скриптов 04 и 20 (исторические, не редактируются) для НОВОЙ базы
--  по-прежнему сеют `boxberry` и тексты с «Boxberry» — новый стенд расходится
--  с живым состоянием. Скрипт выравнивает НОВУЮ базу после посева.
--
--  GUARD (защита правок владельца): обе замены идут ПО СТАРОМУ ЗНАЧЕНИЮ —
--  `where code = 'boxberry'` и `where value like '%Boxberry%'`. На живой
--  базе (где переименование уже сделано) скрипт — no-op: 0 строк изменено,
--  существующие значения НЕ перезаписываются. Повторный прогон безопасен
--  (guard), но по регламенту data-миграция выполняется один раз.
