--       строкой бэкапа 06.10.2026);
--    2. site_content: «Boxberry» → «Почта России» в текстах ключей
--       order.delivery.text, adv.3.text, checkout.hint.address (посевы 04/20;
--       статические fallback-тексты index.html волны v0.16.0 заменены на
--       нейтральные формулировки БЕЗ названий служб — решение аналитика
