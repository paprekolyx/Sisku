-- ----------------------------------------------------------------------------
-- 1. Статусы заказа
-- ----------------------------------------------------------------------------
insert into public.order_statuses (code, name, is_final, sort_order)
select v.code, v.name, v.is_final, v.sort_order
from (values
    ('new',       'Новый',      false, 1),
    ('confirmed', 'Подтверждён', false, 2),
    ('packing',   'Сборка',     false, 3),
    ('shipped',   'Отправлен',  false, 4),
    ('delivered', 'Доставлен',  true,  5),
    ('cancelled', 'Отменён',    true,  6),
    ('returned',  'Возврат',    true,  7)
) as v(code, name, is_final, sort_order)
where not exists (select 1 from public.order_statuses s where s.code = v.code);

-- ----------------------------------------------------------------------------
-- 2. Модель переходов (Jira-like workflow)
-- ----------------------------------------------------------------------------
insert into public.status_transitions (from_status_id, to_status_id)
select a.id, b.id
from (values
    ('new',       'confirmed'),
    ('new',       'cancelled'),
    ('confirmed', 'packing'),
    ('confirmed', 'cancelled'),
    ('packing',   'shipped'),
    ('shipped',   'delivered'),
    ('delivered', 'returned')
) as v(from_code, to_code)
join public.order_statuses a on a.code = v.from_code
join public.order_statuses b on b.code = v.to_code
where not exists (
    select 1 from public.status_transitions t
    where t.from_status_id = a.id and t.to_status_id = b.id
);

