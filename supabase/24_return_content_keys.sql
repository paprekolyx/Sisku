do $$
begin
    if to_regclass('public.site_content') is null then
        raise exception 'Sisku draft: не найдена таблица site_content. Проверьте переключатель проектов Supabase слева вверху: нужен проект sisku-draft, а не учебный.';
    end if;
end $$;

-- ----------------------------------------------------------------------------
-- 1. Новые ключи
