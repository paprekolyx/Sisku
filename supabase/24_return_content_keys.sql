-- ----------------------------------------------------------------------------
-- 2. Самопроверка
-- ----------------------------------------------------------------------------
select
    (select count(*) from public.site_content
      where key in ('returns.cta.track','returns.form.title','returns.form.hint',
                    'returns.form.order','returns.form.code','returns.form.reason',
                    'returns.form.reason.placeholder','returns.form.comment',
                    'returns.form.comment.placeholder','returns.form.photo',
                    'returns.form.photo.note','returns.form.submit','returns.form.success',
                    'returns.status.created','returns.status.returned_to_stock',
                    'returns.status.verified','returns.status.rejected','returns.stats.title'))
                                                       as wave_keys,      -- ждём 18
    (select count(*) from public.site_content)         as total_keys,     -- ждём 70 (52 + 18)
    (select count(*) from public.site_content
      where key like 'returns.%')                      as returns_keys,   -- ждём 18 (столько же — в draft_returns_bundle)
    (select value from public.site_content
      where key = 'returns.status.created')            as status_created; -- ждём «Заявка оформлена»
