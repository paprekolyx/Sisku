    ('returns.form.comment.placeholder','Опишите ситуацию подробнее — это ускорит рассмотрение заявки', 'Форма возврата: подсказка в поле комментария'),
    ('returns.form.photo',              'Фото товара', 'Форма возврата: подпись блока фото (заглушка до подключения файлового хранилища — M5)'),
